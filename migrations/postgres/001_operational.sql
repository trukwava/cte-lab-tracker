-- CTE Lab Tracker: proposed PostgreSQL operational schema, v1.
-- Not deployed; requires a controlled provisioning and security review.
-- Deliberately excludes local password credentials, sessions and memberships.
-- The migration exporter adds derived lab_id to dependent rows so PostgreSQL
-- can enforce cross-lab relationships with composite foreign keys.
-- The application must NOT switch its SQLITE backend to this schema until
-- role-scoped PostgreSQL queries and audited import orchestration exist.
BEGIN;
CREATE TABLE organizations (
  id text PRIMARY KEY, name text NOT NULL
);
CREATE TABLE labs (
  id text PRIMARY KEY, name text NOT NULL, demo integer NOT NULL DEFAULT 1 CHECK (demo IN (0,1))
);
CREATE TABLE organization_labs (
  lab_id text PRIMARY KEY REFERENCES labs(id),
  organization_id text NOT NULL REFERENCES organizations(id),
  UNIQUE (organization_id,lab_id)
);
CREATE TABLE locations (
  id text PRIMARY KEY, lab_id text NOT NULL REFERENCES labs(id),
  name text NOT NULL, UNIQUE (lab_id,id)
);
CREATE TABLE borrower_refs (
  code text PRIMARY KEY, lab_id text NOT NULL REFERENCES labs(id),
  label text NOT NULL, UNIQUE (lab_id,code)
);
CREATE TABLE vendor_refs (
  id text PRIMARY KEY, lab_id text NOT NULL REFERENCES labs(id),
  name text NOT NULL, catalog_ref text, last_checked date NOT NULL,
  UNIQUE (lab_id,id)
);
CREATE TABLE assets (
  id text PRIMARY KEY, lab_id text NOT NULL REFERENCES labs(id),
  tag text NOT NULL UNIQUE, category text NOT NULL, make_model text NOT NULL,
  serial_ref text,
  home_location_id text,
  current_location_id text,
  condition text NOT NULL CHECK (condition IN ('good','worn','damaged','unknown')),
  status text NOT NULL CHECK (status IN ('available','on_loan','missing','quarantined','inspection_required','in_service')),
  current_plan_id bigint,
  created_at timestamptz NOT NULL,
  UNIQUE (lab_id,id),
  FOREIGN KEY (lab_id,home_location_id) REFERENCES locations(lab_id,id),
  FOREIGN KEY (lab_id,current_location_id) REFERENCES locations(lab_id,id)
);
CREATE TABLE asset_tags (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lab_id text NOT NULL, asset_id text NOT NULL,
  identifier text NOT NULL UNIQUE, created_at timestamptz NOT NULL,
  FOREIGN KEY (lab_id,asset_id) REFERENCES assets(lab_id,id)
);
CREATE TABLE maintenance_plan_versions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lab_id text NOT NULL, asset_id text NOT NULL,
  version integer NOT NULL, interval_days integer NOT NULL CHECK(interval_days BETWEEN 1 AND 3650),
  effective_at timestamptz NOT NULL, base_date date NOT NULL, next_due_date date NOT NULL,
  UNIQUE (lab_id,asset_id,id), UNIQUE (asset_id,version),
  FOREIGN KEY (lab_id,asset_id) REFERENCES assets(lab_id,id)
);
ALTER TABLE assets ADD CONSTRAINT asset_current_plan_fk
  FOREIGN KEY (lab_id,id,current_plan_id) REFERENCES maintenance_plan_versions(lab_id,asset_id,id)
  DEFERRABLE INITIALLY DEFERRED;
CREATE TABLE asset_vendor_refs (
  lab_id text NOT NULL, asset_id text NOT NULL, vendor_id text NOT NULL,
  PRIMARY KEY (asset_id,vendor_id),
  FOREIGN KEY (lab_id,asset_id) REFERENCES assets(lab_id,id),
  FOREIGN KEY (lab_id,vendor_id) REFERENCES vendor_refs(lab_id,id)
);
CREATE TABLE loans (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lab_id text NOT NULL, asset_id text NOT NULL, borrower_code text NOT NULL,
  issued_at timestamptz NOT NULL, due_at timestamptz NOT NULL,
  returned_at timestamptz,
  checkout_condition text NOT NULL, return_condition text,
  return_location_id text, issued_by text NOT NULL, returned_by text,
  UNIQUE (lab_id,asset_id,id),
  FOREIGN KEY (lab_id,asset_id) REFERENCES assets(lab_id,id),
  FOREIGN KEY (lab_id,borrower_code) REFERENCES borrower_refs(lab_id,code),
  FOREIGN KEY (lab_id,return_location_id) REFERENCES locations(lab_id,id)
);
CREATE UNIQUE INDEX only_one_active_loan_per_asset ON loans(asset_id) WHERE returned_at IS NULL;
CREATE TABLE condition_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lab_id text NOT NULL, asset_id text NOT NULL, loan_id bigint,
  condition text NOT NULL, notes text, actor text NOT NULL, recorded_at timestamptz NOT NULL,
  FOREIGN KEY (lab_id,asset_id) REFERENCES assets(lab_id,id),
  FOREIGN KEY (lab_id,asset_id,loan_id) REFERENCES loans(lab_id,asset_id,id)
);
CREATE TABLE quarantines (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lab_id text NOT NULL, asset_id text NOT NULL,
  reason text NOT NULL, opened_at timestamptz NOT NULL, opened_by text NOT NULL,
  closed_at timestamptz, closed_by text, release_note text,
  FOREIGN KEY (lab_id,asset_id) REFERENCES assets(lab_id,id)
);
CREATE UNIQUE INDEX only_one_open_quarantine ON quarantines(asset_id) WHERE closed_at IS NULL;
CREATE TABLE service_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lab_id text NOT NULL, asset_id text NOT NULL, plan_version_id bigint NOT NULL,
  serviced_date date NOT NULL, next_due_date date NOT NULL,
  notes text NOT NULL, reference text, actor text NOT NULL, recorded_at timestamptz NOT NULL,
  FOREIGN KEY (lab_id,asset_id) REFERENCES assets(lab_id,id),
  FOREIGN KEY (lab_id,asset_id,plan_version_id) REFERENCES maintenance_plan_versions(lab_id,asset_id,id)
);
CREATE TABLE purchase_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lab_id text NOT NULL REFERENCES labs(id), asset_id text,
  item_name text NOT NULL, quantity integer NOT NULL CHECK(quantity>0),
  reason text NOT NULL, vendor_id text, estimated_unit_price_cents integer,
  approval_status text NOT NULL CHECK(approval_status IN ('draft','sent_for_review','externally_approved','declined')),
  created_by text NOT NULL, created_at timestamptz NOT NULL,
  FOREIGN KEY (lab_id,asset_id) REFERENCES assets(lab_id,id),
  FOREIGN KEY (lab_id,vendor_id) REFERENCES vendor_refs(lab_id,id)
);
CREATE TABLE approvals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lab_id text NOT NULL REFERENCES labs(id), asset_id text,
  action text NOT NULL, note text NOT NULL, actor text NOT NULL, created_at timestamptz NOT NULL,
  FOREIGN KEY (lab_id,asset_id) REFERENCES assets(lab_id,id)
);
CREATE TABLE audit_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lab_id text NOT NULL REFERENCES labs(id), entity text NOT NULL,
  entity_id text NOT NULL, action text NOT NULL, actor text NOT NULL,
  details_json jsonb NOT NULL, created_at timestamptz NOT NULL
);
CREATE TABLE import_batches (
  id text PRIMARY KEY, lab_id text NOT NULL REFERENCES labs(id),
  created_by text NOT NULL, created_at timestamptz NOT NULL, raw_csv text NOT NULL DEFAULT '',
  UNIQUE (lab_id,id)
);
CREATE TABLE import_rows (
  lab_id text NOT NULL, batch_id text NOT NULL, row_number integer NOT NULL,
  asset_id text NOT NULL, original_json jsonb, normalized_json jsonb,
  PRIMARY KEY (batch_id,row_number),
  FOREIGN KEY (lab_id,batch_id) REFERENCES import_batches(lab_id,id),
  FOREIGN KEY (lab_id,asset_id) REFERENCES assets(lab_id,id)
);
-- Any user-facing roles or data access MUST be bound independently to a
-- verified production identity and tenant. This DDL alone does not implement RLS.
COMMIT;
